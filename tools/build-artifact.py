#!/usr/bin/env python3
"""Build the Claude-hosted copy of JARVIS-X into ../jarvis-x-artifact.

- index.html without its document wrapper (the Artifact host adds one)
- css/, js/, assets/ copied as-is
- launchers published under web-safe names (*.txt) and listed in js/core/filelist.js,
  so the in-app "Download for my computer" button can rebuild the real zip.
Prints the `files` map for the Artifact publish call.
"""
import json, os, shutil, sys
SRC = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DST = os.path.join(os.path.dirname(SRC), 'jarvis-x-artifact')
os.makedirs(DST, exist_ok=True)
for d in ('css', 'js', 'assets'):
    shutil.rmtree(os.path.join(DST, d), ignore_errors=True)
    shutil.copytree(os.path.join(SRC, d), os.path.join(DST, d))
shutil.rmtree(os.path.join(DST, 'dl'), ignore_errors=True)
os.makedirs(os.path.join(DST, 'dl'))

src = open(os.path.join(SRC, 'index.html'), encoding='utf-8').read()
head = src[src.index('<title>'):src.index('</head>')]
head = '\n'.join(l for l in head.split('\n') if 'manifest' not in l)
body = src[src.index('<body>') + 6:src.index('</body>')]
open(os.path.join(DST, 'index.html'), 'w', encoding='utf-8').write(
    '<!-- JARVIS-X (Claude-hosted build): same source as index.html without the document wrapper -->\n' + head.strip() + '\n' + body.strip() + '\n')

# Files that go into the downloadable app zip: (published path, name inside the zip)
entries = ['index.html']
for d in ('css', 'js', 'assets'):
    for root, _, files in os.walk(os.path.join(DST, d)):
        for f in sorted(files):
            entries.append(os.path.relpath(os.path.join(root, f), DST).replace(os.sep, '/'))
extras = ['manifest.webmanifest', 'sw.js', 'sandbox.html', 'README.md', 'launcher/serve.mjs', 'launcher/serve.ps1',
          'Start JARVIS-X (Windows).bat', 'Start JARVIS-X (Mac).command', 'start-jarvis-x.sh']
for i, name in enumerate(extras):
    pub = f'dl/{i:02d}-' + name.replace('/', '_').replace(' ', '_').replace('(', '').replace(')', '') + '.txt'
    shutil.copyfile(os.path.join(SRC, name), os.path.join(DST, pub))
    entries.append({'src': pub, 'name': name})
entries = [e for e in entries if e != 'js/core/filelist.js'] + ['js/core/filelist.js']
open(os.path.join(DST, 'js/core/filelist.js'), 'w').write(
    '/** Files of the downloadable app (generated by tools/build-artifact.py). */\nexport const FILES = ' + json.dumps(entries, indent=0) + ';\n')

files = {}
for root, _, fs in os.walk(DST):
    for f in fs:
        rel = os.path.relpath(os.path.join(root, f), DST).replace(os.sep, '/')
        if rel != 'index.html':
            files[rel] = rel
json.dump(files, open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(DST, '..', 'artifact-files.json'), 'w'))
print(len(files), 'files')
